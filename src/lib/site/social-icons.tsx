/**
 * Brand marks for the twelve networks in `SOCIAL_NETWORKS`.
 *
 * This file exists because of a comment I wrote in `block-render.tsx`: socials
 * rendered as plain text because "this app has no icon set for twelve
 * networks". Now it has one, and it costs nothing — twelve path strings, no
 * package, no sprite sheet, no network request. An icon library would ship
 * three thousand glyphs so we could use twelve, and would put a runtime
 * dependency in the render path of a page that is otherwise pure server HTML.
 *
 * The paths are from Simple Icons (CC0 1.0 — public domain), except LinkedIn's,
 * which is not in Simple Icons: LinkedIn had it removed on trademark grounds.
 * See LINKEDIN_NOTE below.
 *
 * THE ICONS ARE DECORATIVE AND THE LABEL IS NOT. Every mark here is rendered
 * `aria-hidden` beside its network name in text. That is not belt-and-braces —
 * it is the only arrangement that works. An icon-only chip has to carry the
 * meaning itself, which needs both an accessible name bolted on and a 3:1
 * contrast ratio it cannot always reach (see `whatsapp`), and it asks the
 * viewer to recognise twelve silhouettes. The word "Bluesky" has none of those
 * problems.
 */

