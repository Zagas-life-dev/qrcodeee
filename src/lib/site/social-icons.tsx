/**
 * A network's brand mark.
 *
 * `aria-hidden` with no title, always: this renders next to the network name in
 * text, and a screen reader announcing "Instagram Instagram @kachi" is worse
 * than one announcing nothing here. Callers that genuinely have no adjacent
 * label must supply their own accessible name on the interactive element.
 *
 * `focusable="false"` is not decoration — legacy Edge and IE put SVGs in the
 * tab order without it, which would double the tab stops on a twelve-chip row.
 */
export function SocialIcon({
  network,
  className,
  brandColor = true,
}: {
  network: SocialNetwork;
  className?: string;
  /** Off draws the mark in `currentColor`, for tinted or inverted surfaces. */
  brandColor?: boolean;
}) {
  const icon = SOCIAL_ICONS[network];
  if (!icon) return null;

  return (
    <svg
      viewBox="0 0 24 24"
      aria-hidden
      focusable="false"
      className={className}
      // Inline fill rather than a Tailwind class: these are twelve arbitrary
      // brand hexes, which is exactly the case JIT class generation cannot
      // cover without a safelist that then has to be kept in sync with this file.
      fill={brandColor ? icon.brand : "currentColor"}
    >
      <path d={icon.path} />
    </svg>
  );
}
